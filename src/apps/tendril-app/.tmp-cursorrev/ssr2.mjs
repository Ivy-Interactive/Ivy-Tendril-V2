reg('StatusLine', ()=>h(UI.StatusLine,{status:'ok',children:'s'}));
reg('Pagination', ()=>h(UI.Pagination,null,h(UI.PaginationContent,null,h(UI.PaginationItem,null,h(UI.PaginationPrevious,{href:'#'})))));
