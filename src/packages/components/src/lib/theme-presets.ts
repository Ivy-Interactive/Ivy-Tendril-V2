const BY_ID = new Map(THEME_PRESETS.map((preset) => [preset.id.toLowerCase(), preset]));

/**
 * `TendrilThemes.GetTheme(id)`: an unknown or blank id resolves to the default rather than throwing,
 * because `config.yaml` is hand-editable and a typo there must not leave the app unstyled.
 */
export function getThemePreset(id: string | null | undefined): ThemePreset {
  const found = id ? BY_ID.get(id.trim().toLowerCase()) : undefined;
  return found ?? BY_ID.get(DEFAULT_THEME_PRESET_ID)!;
}

/**
 * The stylesheet a preset installs: one block for its light colours and one for its dark ones, which is
 * how `tokens.css` itself is arranged. Both are emitted, so the preset survives a theme-mode change and
 * a system `prefers-color-scheme` flip without being re-applied.
 *
 * The selectors are deliberately *more specific* than `tokens.css`'s `:root` and `.dark` rather than
 * merely later in the document: a lazily-loaded chunk's stylesheet is appended when its view first
 * renders, so an override that relied on document order would lose the moment one of those chunks
 * carried the token block. `:root:root` outranks `:root` and `.dark`; `html.dark:root` outranks both
 * and this rule's own light half.
 *
 * The default preset generates nothing at all - see the module note.
 */
export const LIGHT_SELECTOR = ":root:root";
export const DARK_SELECTOR = "html.dark:root";

export function themePresetCss(preset: ThemePreset): string {
  const block = (selector: string, colors: ThemePresetColors | undefined): string => {
    if (!colors) return "";
    const body = Object.entries(colors)
      .map(([token, value]) => `  --${token}: ${value};`)
      .join("\n");
    return body === "" ? "" : `${selector} {\n${body}\n}`;
  };

  return [block(LIGHT_SELECTOR, preset.colors.light), block(DARK_SELECTOR, preset.colors.dark)]
    .filter((part) => part !== "")
    .join("\n");
}

/**
 * Applies a preset, mirroring `TendrilThemes.ApplyTheme(client, themeId)`.
 *
 * The generated CSS goes into one `<style>` element appended to `<head>`, so it wins over
 * `tokens.css` on document order at equal specificity, and switching preset replaces its contents
 * rather than accumulating layers. Returns the preset that actually applied, which is the default for
 * an id nothing matches.
 */
export function applyThemePreset(
  id: string | null | undefined,
  doc: Document | undefined = typeof document === "undefined" ? undefined : document,
): ThemePreset {
  const preset = getThemePreset(id);
  if (!doc) return preset;

  const css = themePresetCss(preset);
  const existing = doc.getElementById(THEME_PRESET_STYLE_ID);

  if (css === "") {
    existing?.remove();
    return preset;
  }

  const style = existing ?? doc.createElement("style");
  if (!existing) {
    style.id = THEME_PRESET_STYLE_ID;
    doc.head.appendChild(style);
  }
  style.textContent = css;
  return preset;
}
