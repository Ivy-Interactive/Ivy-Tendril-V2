/**
 * The colour-scheme presets Appearance offers, ported from V1's `Themes/TendrilThemes.cs`.
 *
 * V1 keeps a `TendrilThemeDescriptor` per preset (id, name, description, `IsDark`, four
 * `PreviewColors` and a full Ivy `Theme`), and applies one by generating a stylesheet and handing it
 * to `client.ApplyTheme(css)`. This module keeps both decisions: the table below is those
 * descriptors verbatim, and {@link applyThemePreset} injects one `<style>` element rather than
 * writing inline styles, so the light and dark halves of a preset are both installed at once and a
 * `prefers-color-scheme` flip needs no re-application.
 *
 * The token names are `styles/tokens.css`'s, whose generated region is exactly the 25 colours V1's
 * `ThemeColors` carries. Nothing here edits that region - a preset is an override layer on top of
 * it, and the `default` preset is the absence of that layer, i.e. Tendril's own Ivy-green token set
 * rather than V1's zinc one.
 */

/** One preset's colours for one mode, keyed by the CSS custom property they set (without `--`). */
export type ThemePresetColors = Record<string, string>;

export interface ThemePreset {
  /** `TendrilThemeDescriptor.Id`, and what `config.yaml`'s `theme` key holds. */
  id: string;
  name: string;
  description: string;
  /** Whether the preset was authored dark-first. V1 uses it to pick which half to preview. */
  isDark: boolean;
  /** The four swatches Appearance draws, in V1's order: primary, secondary, accent, background. */
  previewColors: string[];
  colors: { light?: ThemePresetColors; dark?: ThemePresetColors };
  /** A theme published by a connected Team Vault rather than shipped. See the note in the module. */
  isVaultTheme?: boolean;
  vaultName?: string;
}

