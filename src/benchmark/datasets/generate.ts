// Git fixture repos

/**
 * One real single-commit git repo per project. Both apps expect `repos[].path` to be a real repo
 * (V1's PUT /api/plans validates that repo paths exist), and neither writes into it on the paths the
 * benchmark exercises. Repos live outside the homes so config.yaml is byte-identical for both apps
 * and restoring a home never has to rewrite paths. Commit dates are fixed so the sha is stable.
 */
export async function ensureRepos(reposDir: string, projects: readonly string[]): Promise<Record<string, string>> {
  const out: Record<string, string> = {};
  const gitEnv = cleanEnv({
    GIT_AUTHOR_NAME: 'bench',
    GIT_AUTHOR_EMAIL: 'bench@example.invalid',
    GIT_COMMITTER_NAME: 'bench',
    GIT_COMMITTER_EMAIL: 'bench@example.invalid',
    GIT_AUTHOR_DATE: '2026-01-01T00:00:00Z',
    GIT_COMMITTER_DATE: '2026-01-01T00:00:00Z',
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_CONFIG_GLOBAL: '/dev/null',
  });
  for (const pr of projects) {
    const rp = path.join(reposDir, pr);
    out[pr] = rp;
    const ok = await run('git', ['-C', rp, 'rev-parse', '--verify', 'HEAD'], { env: gitEnv }).then(
      () => true,
      () => false,
    );
    if (ok) continue;
    fs.rmSync(rp, { recursive: true, force: true });
    fs.mkdirSync(rp, { recursive: true });
    await run('git', ['init', '-q', '-b', 'main', rp], { env: gitEnv });
    fs.writeFileSync(path.join(rp, 'README.md'), 'bench\n');
    await run('git', ['-C', rp, '-c', 'commit.gpgsign=false', 'add', '.'], { env: gitEnv });
    await run('git', ['-C', rp, '-c', 'commit.gpgsign=false', 'commit', '-q', '--no-verify', '-m', 'init'], { env: gitEnv });
  }
  return out;
}

