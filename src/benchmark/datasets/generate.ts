// Phase 1: config.yaml + Plans/

export interface PlanRecord {
  /** 5-digit id, as used in URLs (`00037`). */
  id: string;
  n: number;
  folder: string;
  title: string;
  state: PlanState;
  project: string;
  level: string;
  createdMs: number;
  updatedMs: number;
}

export interface TemplateResult {
  plans: PlanRecord[];
  projects: string[];
  repoPaths: Record<string, string>;
}

/** Always double-quoted: V2 rejects some unquoted scalars that V1 would auto-quote. */
function q(s: string): string {
  return `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** ISO-8601 UTC with 6 fractional digits and `Z` (V2 needs an offset; V1 accepts any DateTime). */
function isoMicro(ms: number): string {
  return new Date(ms).toISOString().replace(/\.(\d{3})Z$/, (_, frac: string) => `.${frac}000Z`);
}

/** 7 fractional digits, like .NET's round-trip "O" format that V1 writes for job times. */
function isoTicks(ms: number): string {
  return new Date(ms).toISOString().replace(/\.(\d{3})Z$/, (_, frac: string) => `.${frac}0000Z`);
}

function isoSeconds(ms: number): string {
  return new Date(ms).toISOString().replace(/\.\d{3}Z$/, 'Z');
}

/** V1's PlanYamlHelper.ToSafeTitle: PascalCase words, alphanumerics only, at most 24 characters. */
export function safeTitle(title: string): string {
  const safe = title
    .split(' ')
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join('')
    .replace(/[^a-zA-Z0-9]/g, '');
  return safe.length > 24 ? safe.slice(0, 24) : safe;
}

/**
 * Exact state counts from the percentage mix (largest remainder, ties in PLAN_STATES order), so a
 * dataset has precisely the advertised mix instead of a random approximation of it.
 */
export function stateQuotas(total: number, mix: Readonly<Record<PlanState, number>>): Record<PlanState, number> {
  const sum = PLAN_STATES.reduce((a, s) => a + mix[s], 0);
  const exact = PLAN_STATES.map((s) => ({ s, v: (total * mix[s]) / sum }));
  const out = Object.fromEntries(exact.map((e) => [e.s, Math.floor(e.v)])) as Record<PlanState, number>;
  let left = total - PLAN_STATES.reduce((a, s) => a + out[s], 0);
  const byRemainder = exact
    .map((e, i) => ({ ...e, i, r: e.v - Math.floor(e.v) }))
    .sort((a, b) => b.r - a.r || a.i - b.i);
  for (const e of byRemainder) {
    if (left <= 0) break;
    out[e.s]++;
    left--;
  }
  return out;
}

function configYaml(projects: readonly string[], repoPaths: Record<string, string>): string {
  const lines = [
    'codingAgent: claude',
    'telemetry: false',
    // Background work stays at each app's shipped defaults (V2's model enrichment fetch and worktree
    // reaper included): V1's pricing warmup and worktree cleanup have no switch, so disabling only
    // V2's counterparts would hand V2 a quieter idle than a real install has.
    'inbox:',
    '  autoAcceptAssignedIssues: false',
    '  checkIntervalMinutes: 0',
    'desktopNotifications: false',
  ];
  if (projects.length === 0) {
    lines.push('projects: []');
  } else {
    lines.push('projects:');
    projects.forEach((pr, i) => {
      lines.push(`  - name: ${pr}`, `    color: ${PROJECT_COLORS[i % PROJECT_COLORS.length]}`, '    repos:', `      - path: ${q(repoPaths[pr]!)}`, '        baseBranch: main', '    verifications:');
      for (const v of VERIFICATIONS) lines.push(`      - name: ${v}`, '        required: true');
      lines.push('    context: ""');
    });
  }
  lines.push('verifications:');
  for (const v of VERIFICATIONS) lines.push(`  - name: ${v}`, `    prompt: ${q(`Run ${v}`)}`);
  // V2 shows its onboarding wizard for a home without projects; V1 ignores the key.
  if (projects.length === 0) lines.push('onboarding:', '  dismissed: true');
  return `${lines.join('\n')}\n`;
}

function setTimes(p: string, ms: number): void {
  const d = new Date(ms);
  fs.utimesSync(p, d, d);
}

/**
 * Writes config.yaml and Plans/ into `dir` (which must be empty or absent) and pins every mtime to
 * a value derived from the plan dates. Pinned mtimes make the template byte-and-time identical on
 * every rebuild, and give V2's watcher ("newest 500 folders") and incremental sync (mtime vs
 * LastSyncTime) a realistic, stable order instead of "everything written in the same second".
 */
export function writeTemplate(dir: string, spec: DatasetSpec, repoPaths: Record<string, string>): TemplateResult {
  const rnd = mulberry32(seedFrom(`tendril-bench:plans:${spec.seed}`));
  const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rnd() * xs.length)]!;
  const randInt = (lo: number, hi: number) => lo + Math.floor(rnd() * (hi - lo + 1));

  const projects = projectNames(spec);
  const plansDir = path.join(dir, 'Plans');
  fs.mkdirSync(plansDir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'config.yaml'), configYaml(projects, repoPaths));

  const quotas = stateQuotas(spec.plans, spec.stateMix);
  const states: PlanState[] = PLAN_STATES.flatMap((s) => Array<PlanState>(quotas[s]).fill(s));
  for (let i = states.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [states[i], states[j]] = [states[j]!, states[i]!];
  }

  const plans: PlanRecord[] = [];
  for (let n = 1; n <= spec.plans; n++) {
    const title = `${Array.from({ length: 5 }, () => {
      const w = pick(WORDS);
      return w[0]!.toUpperCase() + w.slice(1);
    }).join(' ')} ${n}`;
    const id = String(n).padStart(5, '0');
    const folder = `${id}-${safeTitle(title)}`;
    const fp = path.join(plansDir, folder);
    fs.mkdirSync(path.join(fp, 'Revisions'), { recursive: true });
    fs.mkdirSync(path.join(fp, 'Verification'), { recursive: true });
    const project = projects.length ? projects[n % projects.length]! : 'Auto';
    const state = states[n - 1]!;
    const level = pick(LEVELS);
    const createdMs = BASE_MS + PLAN_STEP_MS * n;
    const updatedMs = createdMs + randInt(5, 600) * 60_000;
    const vstat = state === 'Completed' ? 'Pass' : state === 'Failed' ? 'Fail' : 'Pending';
    const priority = randInt(0, 20);
    const yaml = [
      'schemaVersion: 3',
      `state: ${state}`,
      `project: ${project}`,
      `level: ${level}`,
      `title: ${q(title)}`,
      'repos:',
      `- ${q(repoPaths[project] ?? '/tmp/none')}`,
      `created: ${isoMicro(createdMs)}`,
      `updated: ${isoMicro(updatedMs)}`,
      'prs: []',
      'commits: []',
      'verifications:',
      ...VERIFICATIONS.flatMap((v) => [`- name: ${v}`, `  status: ${vstat}`]),
      'relatedPlans: []',
      'dependsOn: []',
      `priority: ${priority}`,
    ];
    fs.writeFileSync(path.join(fp, 'plan.yaml'), `${yaml.join('\n')}\n`);
    for (let r = 1; r <= spec.revisionsPerPlan; r++) {
      const head = `# ${title}\n\n## Problem\n\nRevision ${r} of plan ${id}.\n\n`;
      const body = PARA.repeat(Math.ceil(spec.revisionBytes / PARA.length) + 1).slice(0, Math.max(0, spec.revisionBytes - head.length));
      fs.writeFileSync(path.join(fp, 'Revisions', `${String(r).padStart(3, '0')}.md`), `${head}${body}\n`);
    }
    for (const v of VERIFICATIONS) {
      fs.writeFileSync(path.join(fp, 'Verification', `${v}.md`), `---\nresult: ${vstat}\ndate: ${isoSeconds(updatedMs)}\n---\n# ${v}\n\nok\n`);
    }
    plans.push({ id, n, folder, title, state, project, level, createdMs, updatedMs });
  }
  fs.writeFileSync(path.join(plansDir, '.counter'), String(spec.plans + 1));

  // Children first: writing into a directory bumps its mtime.
  for (const p of plans) {
    const fp = path.join(plansDir, p.folder);
    for (const sub of ['Revisions', 'Verification']) {
      for (const f of fs.readdirSync(path.join(fp, sub))) setTimes(path.join(fp, sub, f), p.updatedMs);
      setTimes(path.join(fp, sub), p.updatedMs);
    }
    setTimes(path.join(fp, 'plan.yaml'), p.updatedMs);
    setTimes(fp, p.updatedMs);
  }
  const lastMs = plans.reduce((m, p) => Math.max(m, p.updatedMs), BASE_MS);
  setTimes(path.join(plansDir, '.counter'), lastMs);
  setTimes(plansDir, lastMs);
  setTimes(path.join(dir, 'config.yaml'), BASE_MS);
  setTimes(dir, BASE_MS);
  return { plans, projects, repoPaths };
}

