// Hashing

export interface TreeHash {
  /** sha256 over (relative path, size, bytes) of every included file, sorted by path. */
  content: string;
  /** Same plus every file's and directory's mtime (ms), so a rewrite that restores bytes still shows. */
  withTimes: string;
  files: number;
  bytes: number;
}

/** Regular files under `dir` (relative, sorted), skipping what `include` rejects. */
export function listTree(dir: string, include: (rel: string, isDir: boolean) => boolean = () => true): { files: string[]; dirs: string[] } {
  const files: string[] = [];
  const dirs: string[] = [];
  const walk = (rel: string) => {
    for (const e of fs.readdirSync(path.join(dir, rel), { withFileTypes: true })) {
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) {
        if (!include(r, true)) continue;
        dirs.push(r);
        walk(r);
      } else if (e.isFile() && include(r, false)) {
        files.push(r);
      }
    }
  };
  walk('');
  files.sort();
  dirs.sort();
  return { files, dirs };
}

export function hashTree(dir: string, include?: (rel: string, isDir: boolean) => boolean): TreeHash {
  const { files, dirs } = listTree(dir, include);
  const content = crypto.createHash('sha256');
  const timed = crypto.createHash('sha256');
  let bytes = 0;
  for (const rel of files) {
    const p = path.join(dir, rel);
    const buf = fs.readFileSync(p);
    const st = fs.statSync(p);
    bytes += buf.length;
    const head = `${rel}\0${buf.length}\0`;
    content.update(head).update(buf);
    timed.update(head).update(buf).update(`\0${Math.round(st.mtimeMs)}\0`);
  }
  for (const rel of dirs) timed.update(`${rel}/\0${Math.round(fs.statSync(path.join(dir, rel)).mtimeMs)}\0`);
  return { content: content.digest('hex'), withTimes: timed.digest('hex'), files: files.length, bytes };
}

/** The part of a home both apps must see identically: config.yaml and everything under Plans/. */
export function sharedContent(rel: string, isDir: boolean): boolean {
  const top = rel.split('/')[0]!;
  if (isDir) return top === 'Plans';
  return rel === 'config.yaml' || top === 'Plans';
}

export function sha256(data: string | Buffer): string {
  return crypto.createHash('sha256').update(data).digest('hex');
}
