// Synthetic TENDRIL_HOME content that both Tendril V1 (v1.2.4) and V2 accept, ported from the
// research prototype gen_dataset.py. Generation is split into phases because each app's own
// migrate step has to run between writing the plans and inserting the jobs:
//
//   1. writeTemplate: config.yaml + Plans/ (files and mtimes fully determined by the spec's seed)
//   2. <app>.migrate(home): the app's own CLI creates tendril.db (datasets/index.ts drives this)
//   3. insertJobs: the same terminal job rows into each app's tendril.db, then a WAL checkpoint
//
// Every rule below exists because one of the two apps rejects or rewrites anything else (see the
// v1-data/v2-data research): schemaVersion 3 (or both apps migrate and rewrite plan.yaml), dates with
// an offset (V2 skips the plan otherwise), exact-case verification statuses (V2 skips) and colours
// (V1 rewrites config.yaml), at least one Revisions/*.md (V1 hides the plan), terminal job statuses
// only (queued ones would be executed), int32 job counters (V1 reads them with GetInt32).

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { PLAN_STATES, type DatasetSpec, type PlanState } from '../lib/config.ts';
import { cleanEnv, run } from '../lib/proc.ts';
import { mulberry32, seedFrom } from '../lib/stats.ts';

/** Bumped whenever the generated bytes change, so `datasets` knows a template is stale. */
export const GENERATOR_VERSION = 3;

/** Exact-case Ivy `Colors` names; anything else makes V1 rewrite config.yaml. */
const PROJECT_COLORS = ['Blue', 'Green', 'Purple', 'Orange', 'Teal', 'Rose', 'Amber', 'Indigo'];
export const VERIFICATIONS = ['Build', 'Test', 'Lint'] as const;
/** Levels both apps ship as defaults, so no `levels:` block is needed in config.yaml. */
const LEVELS = ['Bug', 'Feature', 'Chore'];
const WORDS = 'alpha beta gamma delta sidebar cache worker token plan render stream socket queue index'.split(' ');
const PARA = 'Lorem ipsum dolor sit amet, consectetur adipiscing elit. '.repeat(40);
const JOB_STATUSES = ['Completed', 'Completed', 'Completed', 'Completed', 'Completed', 'Completed', 'Completed', 'Completed', 'Failed', 'Stopped'];

/** All generated timestamps count from here (fixed, so the bytes never depend on the build date). */
export const BASE_MS = Date.UTC(2026, 0, 1, 0, 0, 0);
/** Plan n is created 37 min after plan n-1; job j starts 13 min after job j-1 (as in the prototype). */
const PLAN_STEP_MS = 37 * 60_000;
const JOB_STEP_MS = 13 * 60_000;

export function projectNames(spec: DatasetSpec): string[] {
  return Array.from({ length: spec.projects }, (_, i) => `BenchProject${i + 1}`);
}

