// Phase 3: jobs

export interface JobRow {
  Id: string;
  Type: string;
  PlanFile: string;
  Project: string;
  Status: string;
  Provider: string;
  StartedAt: string;
  CompletedAt: string;
  DurationSeconds: number;
  Cost: number;
  Tokens: number;
  Cleared: number;
  Model: string;
  InputTokens: number;
  OutputTokens: number;
}

/**
 * The job rows for a dataset (pure; same rows for both apps). The portable row from the v2-data
 * research: Args/TypedArgs NULL (V2 reads Args, V1 TypedArgs), PlanFile = folder name (V1's meaning,
 * V2 accepts it), exact-case terminal Status (one bad row makes V1 drop its whole job history).
 */
export function planJobs(spec: DatasetSpec, plans: readonly PlanRecord[]): JobRow[] {
  const rnd = mulberry32(seedFrom(`tendril-bench:jobs:${spec.seed}`));
  const pick = <T>(xs: readonly T[]): T => xs[Math.floor(rnd() * xs.length)]!;
  const randInt = (lo: number, hi: number) => lo + Math.floor(rnd() * (hi - lo + 1));
  const rows: JobRow[] = [];
  for (let j = 1; j <= spec.jobs; j++) {
    const plan = plans.length ? plans[(j - 1) % plans.length]! : null;
    const startedMs = BASE_MS + JOB_STEP_MS * j;
    const dur = randInt(30, 3600);
    const tin = randInt(1000, 900_000);
    const tout = randInt(100, 90_000);
    rows.push({
      Id: String(j).padStart(5, '0'),
      Type: 'ExecutePlan',
      PlanFile: plan?.folder ?? 'ExecutePlan',
      Project: plan?.project ?? 'Auto',
      Status: pick(JOB_STATUSES),
      Provider: 'claude',
      StartedAt: isoTicks(startedMs),
      CompletedAt: isoTicks(startedMs + dur * 1000),
      DurationSeconds: dur,
      Cost: Math.round((0.01 + rnd() * 4.99) * 10_000) / 10_000,
      Tokens: tin + tout,
      Cleared: 0,
      Model: 'claude-sonnet-4-5',
      InputTokens: tin,
      OutputTokens: tout,
    });
  }
  return rows;
}

const JOB_COLUMNS: ReadonlyArray<keyof JobRow> = [
  'Id',
  'Type',
  'PlanFile',
  'Project',
  'Status',
  'Provider',
  'StartedAt',
  'CompletedAt',
  'DurationSeconds',
  'Cost',
  'Tokens',
  'Cleared',
  'Model',
  'InputTokens',
  'OutputTokens',
];

/**
 * INSERTs the rows into an app-migrated tendril.db in one transaction, writes Jobs/.counter (V1's
 * job id allocator) and truncates the WAL so the snapshot is a single self-contained file.
 */
export function insertJobs(home: string, rows: readonly JobRow[]): void {
  const dbFile = path.join(home, 'tendril.db');
  if (!fs.existsSync(dbFile)) throw new Error(`${dbFile} does not exist: run the app's migrate first`);
  const db = new DatabaseSync(dbFile);
  try {
    if (rows.length) {
      const stmt = db.prepare(`INSERT INTO Jobs (${JOB_COLUMNS.join(', ')}) VALUES (${JOB_COLUMNS.map(() => '?').join(', ')})`);
      db.exec('BEGIN');
      try {
        for (const r of rows) stmt.run(...JOB_COLUMNS.map((c) => r[c]));
        db.exec('COMMIT');
      } catch (e) {
        db.exec('ROLLBACK');
        throw e;
      }
    }
    db.exec('PRAGMA wal_checkpoint(TRUNCATE)');
  } finally {
    db.close();
  }
  if (rows.length) {
    fs.mkdirSync(path.join(home, 'Jobs'), { recursive: true });
    fs.writeFileSync(path.join(home, 'Jobs', '.counter'), String(rows.length + 1));
  }
}

export interface DbFacts {
  userVersion: number;
  journalMode: string;
  tables: string[];
  jobs: number;
  plans: number;
  jobStatuses: Record<string, number>;
}

/** What a migrated template DB contains (for the manifest and for sanity checks). */
export function dbFacts(home: string): DbFacts {
  const db = new DatabaseSync(path.join(home, 'tendril.db'), { readOnly: true });
  try {
    const userVersion = Number((db.prepare('PRAGMA user_version').get() as { user_version: number }).user_version);
    const journalMode = String((db.prepare('PRAGMA journal_mode').get() as { journal_mode: string }).journal_mode);
    const tables = (db.prepare("SELECT name FROM sqlite_master WHERE type='table' ORDER BY name").all() as Array<{ name: string }>).map((r) => r.name);
    const count = (t: string) => (tables.includes(t) ? Number((db.prepare(`SELECT COUNT(*) AS n FROM ${t}`).get() as { n: number }).n) : 0);
    const jobStatuses: Record<string, number> = {};
    if (tables.includes('Jobs')) {
      for (const r of db.prepare('SELECT Status AS s, COUNT(*) AS n FROM Jobs GROUP BY Status ORDER BY Status').all() as Array<{ s: string; n: number }>) jobStatuses[r.s] = Number(r.n);
    }
    return { userVersion, journalMode, tables, jobs: count('Jobs'), plans: count('Plans'), jobStatuses };
  } finally {
    db.close();
  }
}

